void expmv(int n, real_t *bi, real_t* cr, real_t *ci, real_t *sr, real_t *si, real_t *wrk, real_t *er, real_t *ei)
{
  int k, s, l, i, j, l0, m;
  real_t normA, mn, sn, cs, a0, nrm;
  real_t *dr, *di, *xr, *xi;

  dr = wrk;
  di = dr + n;
  xr = di + n;
  xi = xr + n;

  sn = bi[0];
  cs = bi[0];
  for (k = 1; k < n; k++) {
    if (bi[k] < sn)
      sn = bi[k];
    if (bi[k] > cs)
      cs = bi[k];
  }
  mn = 0.5 * (sn + cs);
  sn = _sin(mn);
  cs = _cos(mn);
  for (k = 0; k < n; k++)
    bi[k] -= mn;

  nrm = normA = norm1(n, bi, cr, ci);
  if (normA > inv[0]) {
    s = (int) _ceil(normA / inv[0]);
    normA /= (real_t) s;
  } else {
    s = 1;
  }
  
  m = 14;
  k = 0;
  l0 = 0;
  while (k < 5 && normA <= inv[k+1]) {
    l0 += m;
    k++;
    m -= 2;
  }
  a0 = ca0[k];
  /*
  printf("k=%d, m=%d, nrm=%g, s=%d, l0=%d\n", k, m, normA, s, l0);
  */
  for (k = 0; k < n; k++) {
    bi[k] /= (real_t) s;
    cr[k] /= (real_t) s;
    ci[k] /= (real_t) s;
  }

  for (i = 0; i < s; i++) {

    for (k = 0; k < n; k++) {
      er[k] = a0 * sr[k];
      ei[k] = a0 * si[k];
    }

    for (l = 0; l < m; l++) {
      j = l0 + l;
      for (k = 0; k < n; k++) {
	bi[k] -= cthr[j];
	dr[k] = sr[k];
	di[k] = si[k];
      }
      thomas(n, bi, -cthi[j], ci, cr, dr, di, xr, xi);
      for (k = 0; k < n; k++) {
	bi[k] += cthr[j];
	er[k] += car[j]*xr[k] - cai[j]*xi[k];
	ei[k] += cai[j]*xr[k] + car[j]*xi[k];
      }
    }
    for (l = 0; l < m; l++) {
      j = l0 + l;
      for (k = 0; k < n; k++) {
	bi[k] -= sthr[j];
	dr[k] = sr[k];
	di[k] = si[k];
      }
      thomas(n, bi, -sthi[j], ci, cr, dr, di, xr, xi);
      for (k = 0; k < n; k++) {
	bi[k] += sthr[j];
	er[k] +=  sai[j]*xr[k] + sar[j]*xi[k];
	ei[k] += -sar[j]*xr[k] + sai[j]*xi[k];
      }
    }

    for (k = 0; k < n; k++) {
      sr[k] = er[k];
      si[k] = ei[k];
    }
  }

  for (k = 0; k < n; k++) {
    er[k] = sr[k] * cs - si[k] * sn;
    ei[k] = si[k] * cs + sr[k] * sn;
  }

  *wrk = nrm;
}

