real_t norm1(int n, real_t *b, real_t* cr, real_t *ci)
{
  int k, n1;
  real_t normA, s, m;
  n1 = n - 1;

  m = _sqrt(cr[0] * cr[0] + ci[0] * ci[0]);
  normA = m + _fabs(b[0]);

  for (k = 1; k < n1; k++) {
    s = m + _fabs(b[k]);
    m = _sqrt(cr[k] * cr[k] + ci[k] * ci[k]);
    s += m;
    if (s > normA)
      normA = s;
  }
  s = m + _fabs(b[n1]);
  if (s > normA)
    normA = s;

  return normA;
}


